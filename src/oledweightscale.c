static void draw_text(int x, int y, const char *s) {
    while (*s) {
        int idx = 0;
        if (*s >= 32 && *s <= 90) idx = *s - 32; // Directly maps ASCII to our array
        
        for (int i = 0; i < 5; i++) {
            uint8_t col = font_5x7[idx][i];
            for (int j = 0; j < 7; j++) {
                if (col & (1 << j)) frame_buffer[((y + j) / 8) * SCREEN_WIDTH + (x + i)] |= (1 << ((y + j) % 8));
            }
        }
        x += 6; s++;
    }
}

/* --- High Frequency 80Hz Sensor Thread --- */
void sensor_thread(void *p1, void *p2, void *p3) {
    struct sensor_value rate = { .val1 = HX711_RATE_80HZ };
    sensor_attr_set(hx, HX711_SENSOR_CHAN_WEIGHT, SENSOR_ATTR_SAMPLING_FREQUENCY, &rate);
    
    struct sensor_value val;
    float alpha = 0.15f; // EMA filter strength (Lower = smoother but slower to react)

    while (1) {
        // Blocks exactly until the HX711 80Hz DOUT pulse fires
        if (sensor_sample_fetch(hx) == 0) {
            sensor_channel_get(hx, HX711_SENSOR_CHAN_WEIGHT, &val);
            latest_raw = val.val1;
            
            // Apply Exponential Moving Average (EMA) to kill the noise
            if (filtered_raw == 0.0f) filtered_raw = (float)latest_raw; // Initialize
            filtered_raw = (alpha * (float)latest_raw) + ((1.0f - alpha) * filtered_raw);
        }
    }
}
// Run cooperatively at high priority to never miss an 80Hz tick
K_THREAD_DEFINE(s_tid, 1024, sensor_thread, NULL, NULL, NULL, K_PRIO_COOP(1), 0, 0);

/* --- Display Engine --- */
int main(void) {
    gpio_pin_configure_dt(&btn, GPIO_INPUT);
    struct display_buffer_descriptor desc = { .buf_size = 1024, .width = 128, .height = 64, .pitch = 128 };
    char buf[32];

    while (1) {
        memset(frame_buffer, 0, 1024);

        /* 1. Calculate the real weight using the smoothed data */
        float weight = (filtered_raw - tare_offset) / scale_factor;

        /* 2. Top Line: Filtered Grams */
        snprintf(buf, sizeof(buf), "GRAMS: %d", (int)weight);
        draw_text(0, 10, buf);

        /* 3. Bottom Line: Raw Unfiltered ADC */
        snprintf(buf, sizeof(buf), "RAW: %d", latest_raw);
        draw_text(0, 45, buf);

        /* Tare logic: Zero out the scale if button is pressed */
        if (gpio_pin_get_dt(&btn)) {
            tare_offset = filtered_raw;
        }

        /* Blast to OLED */
        display_write(disp, 0, 0, &desc, frame_buffer);
        
        /* Yield to let other things run, refreshing screen at a smooth ~40Hz */
        k_sleep(K_MSEC(25)); 
    }
}